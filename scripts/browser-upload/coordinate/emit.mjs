// Local reproducible source packaging. No browser, website or upload calls.
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const directory = new URL('./', import.meta.url);
const hostPaths = ['src/native-action-ledger.js', 'src/native-step-session.js'];
const core = '../private-draft-transfer.mjs';
const definitions = paths => paths.map(path => {
  const source = readFileSync(new URL(path, directory), 'utf8').replace(/^import[^\n]*;\n/gm, '').replace(/^export /gm, '');
  if (/^import\s|^export\s/m.test(source)) throw Error('Unsupported source-module boundary: ' + path);
  return '// SOURCE: ' + path + '\n' + source;
}).join('\n\n');
const host = '// Generated by coordinate/emit.mjs; complete pure definitions only.\n// Current official host review and acceptance are still required.\n\n'
  + definitions(hostPaths)
  + '\nexport {createNativeActionLedger, createNativeStepSession};\n';
const parent = '// Generated by coordinate/emit.mjs; COMPLETE PARENT-ONLY definitions.\n// Credentials and genuine tool receipts stay in original parent memory.\n\n'
  + definitions(['src/coordinate-contract.js', 'src/parent-import-gate.js', 'src/tracked-observations.js', 'src/parent-step-bridge.js', 'src/complete-call-budget.js', core])
  + '\nexport {createPrivateDraftTransfer, createParentImportGate, createTrackedParentObservations, createParentNativeStepBridge, composeCompleteOrdinaryCode, measureCompleteCallBudget};\n';
const files = [['host-program.mjs', host], ['parent-program.mjs', parent]];
const records = files.map(([path, source]) => {
  const bytes = Buffer.from(source);
  writeFileSync(new URL(path, directory), bytes);
  return {path, size: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex')};
});
writeFileSync(new URL('source-manifest.json', directory), JSON.stringify({production_base: '28e37238ffd0fad524629b7f47fed9e8e514085a', installed_in_cua: false, files: records}, null, 2) + '\n');
process.stdout.write(JSON.stringify(records) + '\n');
