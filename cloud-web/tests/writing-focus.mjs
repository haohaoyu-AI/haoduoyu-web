import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const source = fs.readFileSync('components/writing-focus.ts', 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const exports = {};
vm.runInNewContext(js, { exports, Date });
const { reconcileWritingFocus: update, readWritingFocus, saveWritingFocus } = exports;
const historical = [{ article_id: 'old-writing', state: 'writing' }, { article_id: 'old-failed', state: 'failed' }];
let focus = update(null, historical);
assert.equal(Object.keys(focus.current).length, 0, 'stale historical tasks never grab focus');
const active = { article_id: 'new-one', state: 'writing' };
focus = update(focus, [active, ...historical]);
assert.equal(focus.current['new-one'].open, true, 'new work opens immediately');
focus.current['new-one'].open = false;
focus = update(focus, [active, ...historical]);
assert.equal(focus.current['new-one'].open, false, 'ordinary polling preserves user collapse');
focus.current['new-one'].open = true;
focus = update(focus, [{ ...active, state: 'review_pending', editorial_phase: 'verify_pending' }, ...historical]);
assert.equal(focus.current['new-one'].open, true, 'intermediate review does not imply completion');
focus = update(focus, [{ ...active, state: 'submitted' }, ...historical]);
assert.equal(focus.current['new-one'].open, false, 'terminal transition folds once');
focus.current['new-one'].open = true;
focus = update(focus, [{ ...active, state: 'submitted' }, ...historical]);
assert.equal(focus.current['new-one'].open, true, 'manual read-back survives unchanged terminal polling');
focus = update(focus, [{ article_id: 'new-two', state: 'writing' }, { ...active, state: 'submitted' }, ...historical]);
assert.equal(focus.current['new-one'].open, true, 'other new activity cannot close a manual read-back');
focus = update(focus, [{ article_id: 'new-two', state: 'review_pending', editorial_phase: 'verification_failed' }, { ...active, state: 'submitted' }, ...historical]);
assert.equal(focus.current['new-two'].open, false);
assert.equal(focus.current['new-two'].phase, 'verification_failed', 'failure remains failure');
const backing = new Map();
const storage = { getItem: key => backing.get(key), setItem: (key, value) => backing.set(key, value), removeItem: key => backing.delete(key) };
saveWritingFocus(storage, focus);
assert.equal(readWritingFocus(storage).current['new-one'].open, true, 'refresh restores only UI state');
assert.equal(readWritingFocus(storage, Date.now() + 7 * 60 * 60 * 1000), null, 'old sessions expire');
assert.equal(Object.keys(update(readWritingFocus(storage), historical).current).length, 0, 'unreadable IDs cannot restore focus');
saveWritingFocus(storage, null);
assert.equal(readWritingFocus(storage), null, 'auth failure clears saved focus');
assert.equal(readWritingFocus({getItem: () => '{invalid'}), null);
assert.doesNotThrow(() => saveWritingFocus({setItem: () => { throw Error('blocked'); }}, focus));
console.log('PASS: initial history, new activity, review phases, terminal transitions, failure, manual reopening, unrelated polling, reload, expiry, authorization visibility and unavailable storage.');
const outline = {task_id:'outline-1',article_id:null,state:'outline_pending',editorial_phase:'outline_pending'};
let outlineFocus = update(null, [outline], ['outline-1']);
assert.equal(outlineFocus.current['outline-1'].open, true, 'explicit new helper start focuses its authorized readable ID');
outlineFocus = update(outlineFocus, [{...outline,article_id:'article-created-later',state:'body_review_pending'}]);
assert.equal(Object.keys(outlineFocus.current).length, 1, 'article creation keeps the stable task identity');
outlineFocus = update(outlineFocus, [{...outline,state:'blocked'}]);
assert.equal(outlineFocus.current['outline-1'].open, false, 'blocked is stopped, not success');
assert.equal(outlineFocus.current['outline-1'].phase, 'blocked');
assert.equal(Object.keys(update(null, historical, ['unreadable-other-owner-id']).current).length, 0);
console.log('PASS: outline task identity, explicit helper start, owner-readable-ID validation, body-stage continuation and blocked terminal.');
const finished = update(update(null, historical), [{article_id:'done',state:'writing'},...historical]);
const folded = update(finished, [{article_id:'done',state:'submitted'},...historical]);
const nextOperation = update(folded, [{article_id:'next',state:'writing'},{article_id:'done',state:'submitted'},...historical]);
assert.equal(nextOperation.current.done, undefined, 'completed folded work returns to history on the next operation');
assert.equal(nextOperation.current.next.open, true);
console.log('PASS: next operation clears only completed folded focus, retaining the article in history.');
assert.equal(exports.focusPhase({state:'outline_pending',stages:[{stage:'outline',state:'claimed'}]}), 'outline_pending');
assert.equal(exports.focusPhase({state:'outline_pending',stages:[{stage:'outline',state:'requested'}]}), 'outline_generating');
assert.equal(exports.focusPhase({state:'approved',stages:[{stage:'body',state:'claimed'}]}), 'approved');
assert.equal(exports.focusPhase({state:'approved',stages:[{stage:'body',state:'requested'}]}), 'body_generating');
console.log('PASS: claimed/pending is distinct from actual provider generation in both stages.');
